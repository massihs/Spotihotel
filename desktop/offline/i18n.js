export function translator(locale) {
  const lang = (locale ?? "fa").slice(0, 2);
  const dict = STRINGS[lang] ?? STRINGS.fa;
  return (key, values = {}) =>
    (dict[key] ?? STRINGS.fa[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ""));
}
export const isRtl = (locale) => ["fa", "ar"].includes((locale ?? "fa").slice(0, 2));
